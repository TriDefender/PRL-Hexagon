#ifndef PRL_COMPACT_FORMAT_H
#define PRL_COMPACT_FORMAT_H
/* Factor bytes are preinterleaved for 128-byte HVX vlut32: factor[j],factor[j+64]. */
#define PRL_COMPACT_FLAG 65536
#define PRL_COMPACT_BASE_BYTES (2048u*2048u)
#define PRL_COMPACT_TABLE_BYTES (2048u*128u)
#define PRL_COMPACT_P_OFFSET PRL_COMPACT_TABLE_BYTES
#define PRL_COMPACT_Q_OFFSET (PRL_COMPACT_P_OFFSET+2048u)
#define PRL_COMPACT_NONCE_OFFSET (PRL_COMPACT_Q_OFFSET+2048u)
#define PRL_COMPACT_RECORD_BYTES (PRL_COMPACT_NONCE_OFFSET+128u)
#define PRL_COMPACT_TOTAL_BYTES(n) (PRL_COMPACT_BASE_BYTES+(unsigned)(n)*PRL_COMPACT_RECORD_BYTES)
#endif
